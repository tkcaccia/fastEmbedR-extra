#!/usr/bin/env bash

# Runtime contract for the validated fastEmbedR benchmark image. Keep the
# R 4.6 installation paired with the library into which fastEmbedR was built.
FASTEMBEDR_R_PREFIX="${FASTEMBEDR_R_PREFIX:-/opt/r46}"
FASTEMBEDR_RSCRIPT="${FASTEMBEDR_RSCRIPT:-$FASTEMBEDR_R_PREFIX/bin/Rscript}"
FASTEMBEDR_R_LIBRARY="${FASTEMBEDR_R_LIBRARY:-$FASTEMBEDR_R_PREFIX/lib/R/library}"
FASTEMBEDR_CONDA_PREFIX="${FASTEMBEDR_CONDA_PREFIX:-/opt/conda}"
FASTEMBEDR_PYTHON="${FASTEMBEDR_PYTHON:-$FASTEMBEDR_CONDA_PREFIX/bin/python}"

FASTEMBEDR_CONTAINER_PATH="${FASTEMBEDR_CONTAINER_PATH:-/usr/bin:/bin:/usr/sbin:/sbin:$FASTEMBEDR_R_PREFIX/bin:$FASTEMBEDR_CONDA_PREFIX/bin}"
FASTEMBEDR_CONTAINER_LD_LIBRARY_PATH="${FASTEMBEDR_CONTAINER_LD_LIBRARY_PATH:-/.singularity.d/libs:$FASTEMBEDR_R_PREFIX/lib/R/lib:$FASTEMBEDR_R_PREFIX/lib:/opt/rapids/lib:$FASTEMBEDR_CONDA_PREFIX/lib:$FASTEMBEDR_CONDA_PREFIX/targets/x86_64-linux/lib:/usr/local/cuda/lib64:/usr/local/cuda/targets/x86_64-linux/lib:/usr/local/cuda/compat}"

FASTEMBEDR_CONTAINER_BASE_ENV=(
  --env "PATH=$FASTEMBEDR_CONTAINER_PATH"
  --env "LD_LIBRARY_PATH=$FASTEMBEDR_CONTAINER_LD_LIBRARY_PATH"
)

FASTEMBEDR_CONTAINER_R_ENV=(
  "${FASTEMBEDR_CONTAINER_BASE_ENV[@]}"
  --env "R_LIBS=$FASTEMBEDR_R_LIBRARY"
  --env "R_LIBS_SITE=$FASTEMBEDR_R_LIBRARY"
  --env "R_LIBS_USER=$FASTEMBEDR_R_LIBRARY"
  --env "FASTEMBEDR_RSCRIPT=$FASTEMBEDR_RSCRIPT"
  --env "FASTEMBEDR_PYTHON=$FASTEMBEDR_PYTHON"
)
