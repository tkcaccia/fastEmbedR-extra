source(file.path(dirname(sub("^--file=", "", commandArgs(FALSE)[grepl("^--file=", commandArgs(FALSE))][1L])), "common.R"))
args <- parse_cli()
out_dir <- args$out_dir %||% stop("--out-dir is required")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)
status <- tryCatch({
  lock <- read_release_lock(args$release_lock, args$image)
  registry <- load_registry(args$registry %||% file.path(suite_dir(), "datasets.csv"))
  present <- vapply(seq_len(nrow(registry)), function(i) file.exists(file.path(args$data_root, registry$relative_path[[i]])), logical(1))
  datasets <- transform(registry, present = present)
  write.csv(datasets, file.path(out_dir, "dataset_audit.csv"), row.names = FALSE)
  caps <- api_capabilities()
  write.csv(caps, file.path(out_dir, "api_capabilities.csv"), row.names = FALSE)
  write.csv(lock, file.path(out_dir, "validated_release_lock.csv"), row.names = FALSE)
  if (!all(present)) stop("Missing datasets: ", paste(registry$dataset[!present], collapse = ", "))
  if (sum(present) < 15L) warning("Only ", sum(present), " independent datasets are registered; reviewer target is >=15.")
  if (!caps$available[caps$capability == "folds"]) stop("KODAMA.matrix() does not expose folds; fixed five-fold confirmation cannot begin.")
  data.frame(status="pass", detail="Release, datasets, hashes, and confirmatory API passed", stringsAsFactors=FALSE)
}, error = function(e) data.frame(status="fail", detail=conditionMessage(e), stringsAsFactors=FALSE))
write.csv(status, file.path(out_dir, "preflight_status.csv"), row.names = FALSE)
cat(status$status, ": ", status$detail, "\n", sep="")
if (status$status != "pass") quit(status = 2L)

